import React from 'react';
import Container from '@cloudscape-design/components/container';
import Header from '@cloudscape-design/components/header';
import FormField from '@cloudscape-design/components/form-field';
import Input from '@cloudscape-design/components/input';
import Checkbox from '@cloudscape-design/components/checkbox';
import RadioGroup from '@cloudscape-design/components/radio-group';
import SpaceBetween from '@cloudscape-design/components/space-between';
import Alert from '@cloudscape-design/components/alert';

const PASSWORD_CONSTRAINT =
  'Must be at least 8 characters long. Must include at least three of the following mix of character types: uppercase letters (A-Z), lowercase letters (a-z), numbers (0-9), and symbols ! @ # $ % ^ & * ( ) _ + - = [ ] { } |';

export default function UserDetails({ state, setState, errors }) {
  const set = (patch) => setState((s) => ({ ...s, ...patch }));

  return (
    <SpaceBetween size="l">
      <Container header={<Header variant="h2">User details</Header>}>
        <SpaceBetween size="l">
          <div id="section-user-name">
            <FormField
              label="User name"
              constraintText="The user name can have up to 64 characters. Valid characters: A-Z, a-z, 0-9, and + = , . @ _ - (hyphen)"
              errorText={errors.userName}
            >
              <Input
                value={state.userName}
                placeholder="my-user"
                onChange={(e) => set({ userName: e.detail.value })}
                nativeInputAttributes={{ dir: 'ltr' }}
              />
            </FormField>
          </div>

          <div id="section-console-access">
            <SpaceBetween size="m">
              <Checkbox
                checked={state.consoleAccess}
                onChange={(e) => set({ consoleAccess: e.detail.checked })}
                description="If you're providing console access to a person, it's a best practice to manage their access in IAM Identity Center."
              >
                Provide user access to the AWS Management Console — optional
              </Checkbox>

              {state.consoleAccess && (
                <SpaceBetween size="m">
                  <FormField label="Console password">
                    <RadioGroup
                      value={state.passwordType}
                      onChange={(e) => set({ passwordType: e.detail.value })}
                      items={[
                        {
                          value: 'autogenerated',
                          label: 'Autogenerated password',
                          description:
                            'You can view the password after you create the user.',
                        },
                        {
                          value: 'custom',
                          label: 'Custom password',
                          description: 'Enter a custom password for the user.',
                        },
                      ]}
                    />
                  </FormField>

                  {state.passwordType === 'custom' && (
                    <FormField
                      constraintText={PASSWORD_CONSTRAINT}
                      errorText={errors.customPassword}
                    >
                      <SpaceBetween size="xs">
                        <Input
                          type={state.showPassword ? 'text' : 'password'}
                          value={state.customPassword}
                          onChange={(e) =>
                            set({ customPassword: e.detail.value })
                          }
                          nativeInputAttributes={{ dir: 'ltr' }}
                        />
                        <Checkbox
                          checked={state.showPassword}
                          onChange={(e) =>
                            set({ showPassword: e.detail.checked })
                          }
                        >
                          Show password
                        </Checkbox>
                      </SpaceBetween>
                    </FormField>
                  )}

                  <Checkbox
                    checked={state.requireReset}
                    onChange={(e) => set({ requireReset: e.detail.checked })}
                    description="Users automatically get the IAMUserChangePassword policy to allow them to change their own password."
                  >
                    Users must create a new password at next sign-in —
                    Recommended
                  </Checkbox>
                </SpaceBetween>
              )}
            </SpaceBetween>
          </div>
        </SpaceBetween>
      </Container>

      <Alert type="info">
        If you are creating programmatic access through access keys or
        service-specific credentials, you can generate them after you create
        this IAM user.
      </Alert>
    </SpaceBetween>
  );
}
