import React from 'react';
import Container from '@cloudscape-design/components/container';
import Header from '@cloudscape-design/components/header';
import KeyValuePairs from '@cloudscape-design/components/key-value-pairs';
import Table from '@cloudscape-design/components/table';
import Box from '@cloudscape-design/components/box';
import SpaceBetween from '@cloudscape-design/components/space-between';
import FormField from '@cloudscape-design/components/form-field';
import Input from '@cloudscape-design/components/input';
import Button from '@cloudscape-design/components/button';
import Alert from '@cloudscape-design/components/alert';
import { plannedPermissions } from '../mockCreateUser';
import { getPolicy } from '../data';

function Tags({ state, setState }) {
  const updateTag = (index, field, value) =>
    setState((s) => {
      const tags = s.tags.slice();
      tags[index] = { ...tags[index], [field]: value };
      return { ...s, tags };
    });

  return (
    <Container
      header={
        <Header
          variant="h2"
          description="Tags are key-value pairs you can add to AWS resources to help identify, organize, or search for resources. Choose any tags you want to associate with this user."
        >
          Tags — optional
        </Header>
      }
    >
      <SpaceBetween size="xs">
        {state.tags.length === 0 && (
          <Box color="text-body-secondary">
            No tags associated with the resource.
          </Box>
        )}
        {state.tags.map((tag, i) => (
          <SpaceBetween
            key={i}
            direction="horizontal"
            size="xs"
            alignItems="end"
          >
            <FormField label={i === 0 ? 'Key' : undefined}>
              <Input
                placeholder="Enter key"
                value={tag.key}
                onChange={(e) => updateTag(i, 'key', e.detail.value)}
              />
            </FormField>
            <FormField label={i === 0 ? 'Value — optional' : undefined}>
              <Input
                placeholder="Enter value"
                value={tag.value}
                onChange={(e) => updateTag(i, 'value', e.detail.value)}
              />
            </FormField>
            <Button
              onClick={() =>
                setState((s) => ({
                  ...s,
                  tags: s.tags.filter((_, j) => j !== i),
                }))
              }
            >
              Remove
            </Button>
          </SpaceBetween>
        ))}
        <Box>
          <Button
            onClick={() =>
              setState((s) => ({
                ...s,
                tags: [...s.tags, { key: '', value: '' }],
              }))
            }
            disabled={state.tags.length >= 50}
          >
            Add new tag
          </Button>
        </Box>
        <Box variant="small" color="text-body-secondary">
          You can add up to {50 - state.tags.length} more tags.
        </Box>
      </SpaceBetween>
    </Container>
  );
}

export default function ReviewAndCreate({ state, setState, error }) {
  const { policies, groups } = plannedPermissions(state);
  const summary = [
    ...groups.map((name) => ({ name, type: 'Group', usedAs: 'Group' })),
    ...policies.map((name) => ({
      name,
      type: getPolicy(name)?.type || 'AWS managed',
      usedAs: 'Permissions policy',
    })),
  ];

  return (
    <SpaceBetween size="l">
      <div id="section-review">
        <SpaceBetween size="l">
          <Container header={<Header variant="h2">User details</Header>}>
            <KeyValuePairs
              columns={3}
              items={[
                { label: 'User name', value: state.userName },
                {
                  label: 'Console password type',
                  value: !state.consoleAccess
                    ? 'None'
                    : state.passwordType === 'custom'
                      ? 'Custom password'
                      : 'Autogenerated',
                },
                {
                  label: 'Require password reset',
                  value:
                    state.consoleAccess && state.requireReset ? 'Yes' : 'No',
                },
              ]}
            />
          </Container>

          <Table
            header={
              <Header variant="h2" counter={`(${summary.length})`}>
                Permissions summary
              </Header>
            }
            items={summary}
            columnDefinitions={[
              { id: 'name', header: 'Name', cell: (item) => item.name },
              { id: 'type', header: 'Type', cell: (item) => item.type },
              { id: 'usedAs', header: 'Used as', cell: (item) => item.usedAs },
            ]}
            empty={
              <Box textAlign="center" color="inherit">
                No permissions. The user won&apos;t be able to do anything until
                you grant permissions.
              </Box>
            }
          />
        </SpaceBetween>
      </div>

      <div id="section-tags">
        <Tags state={state} setState={setState} />
      </div>

      {error && <Alert type="error">{error}</Alert>}
    </SpaceBetween>
  );
}
