import React, { useEffect, useState } from 'react';
import AppLayout from '@cloudscape-design/components/app-layout';
import TopNavigation from '@cloudscape-design/components/top-navigation';
import SideNavigation from '@cloudscape-design/components/side-navigation';
import BreadcrumbGroup from '@cloudscape-design/components/breadcrumb-group';
import Wizard from '@cloudscape-design/components/wizard';

import UserDetails from './sections/UserDetails';
import SetPermissions from './sections/SetPermissions';
import ReviewAndCreate from './sections/ReviewAndCreate';
import UserView from './sections/UserView';
import TutorialOverlay from './TutorialOverlay';
import {
  mockCreateUser,
  plannedPermissions,
  validatePassword,
  validateUserName,
} from './mockCreateUser';

const initialState = {
  userName: '',
  consoleAccess: false,
  passwordType: 'autogenerated',
  customPassword: '',
  showPassword: false,
  requireReset: true,
  permissionsOption: 'groups',
  selectedGroups: [],
  selectedPolicies: [],
  copyFrom: null,
  tags: [],
};

// The real IAM console's "Create user" flow is a three-step wizard, so this
// lab uses Cloudscape's <Wizard> rather than the single long form (with a
// sticky summary panel) the EC2/S3/VPC labs use.
const WIZARD_SCREENS = ['details', 'permissions', 'review'];

export default function App() {
  const [state, setState] = useState(initialState);
  const [stepIndex, setStepIndex] = useState(0);
  const [errors, setErrors] = useState({});
  const [creating, setCreating] = useState(false);
  const [user, setUser] = useState(null);
  const [showBanner, setShowBanner] = useState(false);

  // One short walkthrough per screen. Each opens automatically the first
  // time its screen is shown — this embed *is* the lab, so students should
  // land straight in the tutorial rather than needing to find it.
  const screen = user ? 'user' : WIZARD_SCREENS[stepIndex];
  const [tutorialActive, setTutorialActive] = useState(true);
  const [tutorialSection, setTutorialSection] = useState('details');
  const [tutorialKey, setTutorialKey] = useState(0);
  const [shownSections, setShownSections] = useState(['details']);

  // This app lives inside an <iframe> on the course page. Modals/panels here
  // are portaled to this document's own body and positioned relative to the
  // iframe's viewport — but if the outer page hasn't scrolled the iframe
  // fully into view yet, that can land below the fold. Same-origin iframes
  // can reach their own <iframe> element via window.frameElement, so we ask
  // the outer page to scroll it into view whenever the tutorial opens.
  //
  // A plain scrollIntoView({block: 'start'}) would align the iframe's top
  // edge with the outer viewport's top edge — but the course page has its
  // own sticky header there, which would then cover the AWS top nav (and
  // the Help button in it). So instead we compute the scroll position
  // ourselves, landing just below that sticky header.
  const scrollEmbedIntoView = () => {
    if (typeof window === 'undefined' || !window.frameElement) return;
    try {
      const parentWindow = window.parent;
      const parentDocument = parentWindow.document;
      const headerHeight =
        parentDocument.querySelector('header')?.getBoundingClientRect()
          .height ?? 0;
      const rect = window.frameElement.getBoundingClientRect();
      const targetY = parentWindow.scrollY + rect.top - headerHeight - 8;
      parentWindow.scrollTo({ top: Math.max(targetY, 0), behavior: 'smooth' });
    } catch {
      // Cross-origin or otherwise inaccessible — fall back to a plain scrollIntoView.
      window.frameElement.scrollIntoView({
        behavior: 'smooth',
        block: 'start',
      });
    }
  };

  useEffect(() => {
    scrollEmbedIntoView();
  }, []);

  // Moving to a new screen: open its walkthrough the first time, otherwise
  // close any walkthrough still pointing at the previous screen's sections.
  useEffect(() => {
    if (!shownSections.includes(screen)) {
      setShownSections((s) => [...s, screen]);
      setTutorialSection(screen);
      setTutorialKey((k) => k + 1);
      setTutorialActive(true);
      scrollEmbedIntoView();
    } else if (tutorialSection !== screen) {
      setTutorialActive(false);
    }
    // Only react to screen changes.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [screen]);

  const openTutorial = () => {
    setTutorialSection(screen);
    setTutorialKey((k) => k + 1);
    setTutorialActive(true);
    scrollEmbedIntoView();
  };

  const validateDetails = () => {
    const next = {
      userName: validateUserName(state.userName),
      customPassword:
        state.consoleAccess && state.passwordType === 'custom'
          ? validatePassword(state.customPassword)
          : null,
    };
    setErrors(next);
    return !next.userName && !next.customPassword;
  };

  const handleNavigate = ({ detail }) => {
    const target = detail.requestedStepIndex;
    if (target > stepIndex) {
      if (stepIndex === 0 && !validateDetails()) return;
      if (stepIndex === 1) {
        const { error } = plannedPermissions(state);
        if (error) {
          setErrors((e) => ({ ...e, permissions: error }));
          return;
        }
      }
    }
    setErrors((e) => ({ ...e, permissions: null, submit: null }));
    setStepIndex(target);
  };

  const handleSubmit = async () => {
    setCreating(true);
    setErrors((e) => ({ ...e, submit: null }));
    try {
      const created = await mockCreateUser(state);
      setUser(created);
      setShowBanner(true);
    } catch (e) {
      setErrors((prev) => ({ ...prev, submit: e.message }));
    } finally {
      setCreating(false);
    }
  };

  const reset = () => {
    setUser(null);
    setState(initialState);
    setErrors({});
    setStepIndex(0);
  };

  const breadcrumbs = [
    { text: 'IAM', href: '#' },
    { text: 'Users', href: '#/users' },
    user
      ? { text: user.userName, href: '#' }
      : { text: 'Create user', href: '#' },
  ];

  return (
    <>
      <div id="top-nav">
        <TopNavigation
          identity={{ href: '#', title: 'AWS' }}
          utilities={[
            // IAM is a global service, so the real console shows "Global"
            // here instead of a Region.
            { type: 'button', text: 'Global', iconName: 'globe' },
            {
              type: 'button',
              text: 'Help',
              iconName: 'status-info',
              variant: 'primary-button',
              onClick: openTutorial,
            },
            { type: 'button', iconName: 'notification' },
            { type: 'button', iconName: 'settings' },
            {
              type: 'menu-dropdown',
              text: 'student@flipthescript.dev',
              iconName: 'user-profile',
              items: [{ id: 'signout', text: 'Sign out' }],
            },
          ]}
          i18nStrings={{
            overflowMenuTriggerText: 'More',
            overflowMenuTitleText: 'All',
          }}
        />
      </div>
      <AppLayout
        headerSelector="#top-nav"
        navigation={
          <SideNavigation
            header={{ text: 'Identity and Access Management (IAM)', href: '#' }}
            activeHref="#/users"
            items={[
              { type: 'link', text: 'Dashboard', href: '#' },
              {
                type: 'section',
                text: 'Access management',
                items: [
                  { type: 'link', text: 'User groups', href: '#' },
                  { type: 'link', text: 'Users', href: '#/users' },
                  { type: 'link', text: 'Roles', href: '#' },
                  { type: 'link', text: 'Policies', href: '#' },
                  { type: 'link', text: 'Identity providers', href: '#' },
                  { type: 'link', text: 'Account settings', href: '#' },
                ],
              },
              {
                type: 'section',
                text: 'Access reports',
                items: [
                  { type: 'link', text: 'Access Analyzer', href: '#' },
                  { type: 'link', text: 'Credential report', href: '#' },
                ],
              },
            ]}
          />
        }
        breadcrumbs={<BreadcrumbGroup items={breadcrumbs} />}
        toolsHide={true}
        content={
          user ? (
            <UserView
              user={user}
              setUser={setUser}
              showBanner={showBanner}
              onDismissBanner={() => setShowBanner(false)}
              onCreateAnother={reset}
            />
          ) : (
            <Wizard
              activeStepIndex={stepIndex}
              onNavigate={handleNavigate}
              onCancel={reset}
              onSubmit={handleSubmit}
              isLoadingNextStep={creating}
              i18nStrings={{
                stepNumberLabel: (n) => `Step ${n}`,
                collapsedStepsLabel: (n, total) => `Step ${n} of ${total}`,
                navigationAriaLabel: 'Steps',
                cancelButton: 'Cancel',
                previousButton: 'Previous',
                nextButton: 'Next',
                submitButton: 'Create user',
                optional: 'optional',
              }}
              steps={[
                {
                  title: 'Specify user details',
                  content: (
                    <UserDetails
                      state={state}
                      setState={setState}
                      errors={errors}
                    />
                  ),
                },
                {
                  title: 'Set permissions',
                  description:
                    'Add user to an existing group or create a new one. Using groups is a best-practice way to manage user permissions by job functions.',
                  content: (
                    <SetPermissions
                      state={state}
                      setState={setState}
                      error={errors.permissions}
                    />
                  ),
                },
                {
                  title: 'Review and create',
                  description:
                    'Review your choices. After you create the user, you can view and download the autogenerated password, if enabled.',
                  content: (
                    <ReviewAndCreate
                      state={state}
                      setState={setState}
                      error={errors.submit}
                    />
                  ),
                },
              ]}
            />
          )
        }
      />
      {tutorialActive && (
        <TutorialOverlay
          key={tutorialKey}
          section={tutorialSection}
          onExit={() => setTutorialActive(false)}
        />
      )}
    </>
  );
}
